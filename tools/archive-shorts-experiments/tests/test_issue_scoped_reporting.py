def fixture():
    payload = dict(raw=[dict(id='source-9', text='정상 원문')], candidates=[dict(
        candidateId='target-9', anchorId='source-9', segmentIds=['source-9'],
        proposedEvidence=[dict(segmentId='source-9', quote='정상 원문')])])
    artifact = dict(schemaVersion='fixture-report-1', artifactHash='frozen-fixture', authorizationHash='authorization-fixture',
                    source=dict(cases=[dict(name='N1', payload=payload)]), plannedUnits=2, reservedCostUsd='0.1')
    # Intentionally shared objects: the original report must keep its raw IDs,
    # while both audit calls independently receive normalized IDs.
    output = dict(verifications=[dict(candidateId='target-9', assessment=dict(
        segmentId='source-9', evidence=[dict(segmentId='source-9', quote='정상 원문')], decision='PASS'))])
    results = [dict(unitIndex=1, case='N1', arm='CANDIDATE', repeat=1, output=output,
                    stages=[dict(stage='JUDGE', estimatedCostUsd='0.0002', providerResponse=dict(raw=output))]),
               dict(unitIndex=2, case='N1', arm='CANDIDATE', repeat=2, output=output,
                    stages=[dict(stage='JUDGE', error='TimeoutError')])]
    return artifact, results


def variant(name):
    artifact, results = fixture()
    kwargs = dict(stopped=False, is_bound=False, simulate=False)
    if name != 'legacy': kwargs['is_bound'] = True
    if name in {'mock', 'mock-partial'}: kwargs['simulate'] = True
    if name in {'partial', 'mock-partial'}: kwargs['stopped'] = True
    if name == 'boundary':
        artifact.update(boundaryInputStudy='fixture-boundary', previewHash='fixture-preview',
                        evaluatedCases=copy.deepcopy(artifact['source']['cases']),
                        normalControlsIncluded=False, repetitionsPerCondition=2)
    if name == 'reselection':
        artifact.update(contextReselectionStudy='fixture-reselection', sourceReportHash='fixture-prior',
                        skipped=[dict(case='C', reason='fixture')], additionalFundingHash='fixture-funding')
    return artifact, results, kwargs


