class ReportingTests(unittest.TestCase):
    def test_historical_report_hashes_and_inputs_are_unchanged(self):
        for name, expected in GOLDEN.items():
            with self.subTest(variant=name):
                artifact, results, kwargs = variant(name)
                before = copy.deepcopy((artifact, results))
                report = build_report(artifact, results, **kwargs)
                self.assertEqual(digest(report), expected)
                self.assertEqual((artifact, results), before)
                self.assertIsNone(report['qualityGateMet'])
                self.assertIsNone(report['actualBilledCostUsd'])
                self.assertEqual(report['unknownCostAttempts'], 1)

    def test_plain_and_bundle_preserve_raw_aliases_and_export_identical_audit(self):
        for bundled in (False, True):
            with self.subTest(bundle=bundled), tempfile.TemporaryDirectory() as tmp:
                artifact, results = fixture()
                if bundled: artifact['reportSerialization'] = 'bundle-1'
                report = build_report(artifact, results, stopped=False, is_bound=True, simulate=True)
                before = copy.deepcopy(report)
                directory = Path(tmp) / 'datasets'
                with patch('urllib.request.OpenerDirector.open', side_effect=AssertionError('network forbidden')):
                    save_reports(directory, artifact, report)
                original = load(directory / 'report-index.json') if bundled else read(directory / 'report.json')
                audit = load(directory / 'audit-index.json') if bundled else read(directory / 'audit-input.json')
                self.assertEqual(original, before)
                self.assertEqual(report, before)
                self.assertEqual(audit['trialSchemaVersion'], 'recorded-flow-regression-1')
                for call in audit['calls']:
                    self.assertEqual(call['output']['verifications'][0]['candidateId'], 'candidate-1')
                    self.assertEqual(call['output']['verifications'][0]['assessment']['segmentId'], 'stt-replay-0')
                self.assertEqual(audit['calls'][0]['stages'][0]['providerResponse']['raw']['verifications'][0]['candidateId'], 'target-9')
                self.assertEqual(audit['cases'][0]['payload']['raw'][0]['text'], '정상 원문')
                if bundled: bundle_hash = digest(audit)
                else: plain_hash = digest(audit)
        self.assertEqual(bundle_hash, plain_hash)

    def test_boundary_audit_keeps_its_separate_trial_contract(self):
        artifact, results, kwargs = variant('boundary')
        report = build_report(artifact, results, **kwargs)
        with tempfile.TemporaryDirectory() as tmp:
            directory = Path(tmp) / 'datasets'
            save_reports(directory, artifact, report)
            audit = read(directory / 'audit-input.json')
        self.assertEqual(audit['trialSchemaVersion'], 'recorded-boundary-input-1')
        self.assertEqual(audit['repetitionsPerCondition'], 2)

    def test_mock_never_reports_api_calls_consumption_or_estimated_charge(self):
        artifact, results, kwargs = variant('mock')
        report = build_report(artifact, results, **kwargs)
        self.assertEqual(report['apiCalls'], 0)
        self.assertEqual(report['simulatedCalls'], 2)
        self.assertEqual(report['consumedReservationUsd'], '0')
        self.assertEqual(report['estimatedCostUsd'], '0')
        self.assertEqual(report['mockTokenRateEquivalentUsd'], '0.0002')
