"""Offline v2 judgment contract. No API transport, budget or runtime integration.

The caller owns request/response association. Digests detect accidental changes,
not malicious rewriting or provider authenticity. Historical v1 responses are
not accepted or repaired here. Structural grounding is not semantic approval.
"""
import copy
import json
import math

from fixed_review_suite import digest, require
from issue_scoped_review import (JUDGMENT_CONTRACT, candidate_input, review_packet,
                                 useful, validate_scope)
from span_catalog_review import judgment_request as catalog_judgment

VERSION = 'server-bound-review-draft-2'
MODEL_FIELDS = {'candidateId', 'relevance', 'usedSelectionIndexes', 'assessment'}
TARGET_TYPES = {'PERSON', 'GROUP', 'REGION', 'RESIDENT_GROUP', 'BUSINESS', 'PRODUCT', 'WORK', 'OTHER'}
GROUNDING_CONTRACT = """
# 필수 근거 선검사
grounding.targetSpanSelected는 실제 TARGET 조각이 선택되었는지만 나타낸다. 의미상 대상 승인이 아니다.
대상 취급 REVIEW_REQUIRED에는 선택된 TARGET과 SAME_ISSUE로 평가한 해당 index의 사용이 필수다.
TARGET이 없으면 CONTEXT를 TARGET으로 바꾸거나 대상 지칭어를 새로 만들지 않는다.
누락 때문에 판단이 불가능하면 UNCERTAIN과 부족한 정보를 반환한다. 정상 해석에 충분한 원문이면 PASS도 가능하다.
표현 자체 검토에는 TARGET이 없어도 된다. 모든 선택에 relevance를 정확히 하나씩 반환한다.
targetType은 PERSON/GROUP/REGION/RESIDENT_GROUP/BUSINESS/PRODUCT/WORK/OTHER만 사용한다.
PASS/UNCERTAIN 또는 target=null에는 TARGET index를 사용하지 않는다.
scopeHash·inputHash·requestHash는 서버 관리용이므로 입력/출력에 넣지 않는다.
후보 가설·정답을 강제로 따르지 않는다. 부재·희망·대체의 연결 자체만으로 폄하를 확정하지 않는다.
"""


def grounding(scope, payload):
    validate_scope(scope, payload)
    c, _ = candidate_input(payload)
    return dict(targetSpanSelected=any(e['role'] == 'TARGET' for e in scope['evidence']),
                targetIssue=c['axis'] == 'TARGET_TREATMENT', semanticTargetApproved=False)


def judgment_request(base, scope):
    payload = json.loads(base['messages'][1]['content'])
    validate_scope(scope, payload)
    body = catalog_judgment(base, scope)
    system = body['messages'][0]['content']
    require(system.count(JUDGMENT_CONTRACT) == 1, 'versioned judgment boundary missing')
    # Versioned contract: no hash generated by the model. Old prompts stay intact.
    system = system.replace(JUDGMENT_CONTRACT, JUDGMENT_CONTRACT.replace(
        ',"scopeHash":"입력 selectedScope의 hash"', ''))
    system = system.replace('scopeHash는 selectedScope.scopeHash 값을 정확히 복사한다. 축약하거나 새 hash를 생성하지 않는다.', '')
    marker = '# 범용 맥락 참고 기준'
    before, reference = system.split(marker, 1)
    body['messages'][0]['content'] = before + GROUNDING_CONTRACT + '\n' + marker + reference
    body['messages'][1]['content'] = json.dumps(dict(
        original=payload, selectedScope=dict(issueSummary=scope['selectionOutput']['issueSummary'],
                                            evidence=copy.deepcopy(scope['evidence'])),
        grounding=grounding(scope, payload)), ensure_ascii=False)
    return body


def prepare_attempt(base, scope, attempt_id, *, judgment_variant=None):
    """Fresh local attempt ID must be assigned by the caller, never by the model."""
    require(useful(attempt_id, 200), 'local attempt ID required')
    payload = json.loads(base['messages'][1]['content'])
    if judgment_variant is None:
        body = judgment_request(base, scope)
    else:
        require(judgment_variant == 'RELATION_CHECKLIST', 'unsupported bound judgment variant')
        from review_boundary_variants import judgment_request as variant_request
        body = variant_request(base, scope, judgment_variant)
    result = dict(schemaVersion=VERSION, attemptId=attempt_id, baseRequest=copy.deepcopy(base),
                  originalInput=payload, selectedScope=copy.deepcopy(scope), requestBody=body,
                  requestHash=digest(body), inputHash=digest(payload), scopeHash=scope['scopeHash'],
                  executionEnabled=False, runtimeUseAuthorized=False)
    if judgment_variant is not None:
        result.update(schemaVersion='server-bound-review-draft-3', judgmentVariant=judgment_variant)
    result['attemptHash'] = digest(result)
    return result


def validate_attempt(attempt):
    require(isinstance(attempt, dict) and attempt == prepare_attempt(
        attempt['baseRequest'], attempt['selectedScope'], attempt['attemptId'],
        judgment_variant=attempt.get('judgmentVariant')), 'local attempt changed')


def parse_response(response, model):
    require(isinstance(response, dict) and response.get('model') == model,
            'provider model mismatch')
    choices = response.get('choices')
    require(isinstance(choices, list) and len(choices) == 1 and isinstance(choices[0], dict)
            and choices[0].get('finish_reason') == 'stop', 'incomplete or ambiguous provider response')
    message = choices[0].get('message')
    require(isinstance(message, dict) and not message.get('refusal') and not message.get('tool_calls')
            and isinstance(message.get('content'), str), 'refusal, tool call or missing content')
    def unique(pairs):
        result = {}
        for key, value in pairs:
            require(key not in result, 'duplicate model JSON key')
            result[key] = value
        return result
    def invalid_constant(value):
        raise ValueError('nonfinite JSON constant: ' + value)
    return json.loads(message['content'], object_pairs_hook=unique, parse_constant=invalid_constant)


def adapt(output, scope, payload):
    require(isinstance(output, dict) and set(output) == MODEL_FIELDS, 'v2 model fields invalid; no legacy hash')
    validate_scope(scope, payload)
    c, _ = candidate_input(payload)
    a = output.get('assessment')
    require(isinstance(a, dict), 'assessment object required')
    target_indexes = [i for i, e in enumerate(scope['evidence']) if e['role'] == 'TARGET']
    used = output.get('usedSelectionIndexes')
    require(isinstance(used, list) and all(type(i) is int for i in used), 'used indexes required')
    if a.get('decision') == 'REVIEW_REQUIRED' and (c['axis'] == 'TARGET_TREATMENT' or a.get('target') is not None):
        require(len(target_indexes) == 1 and target_indexes[0] in used, 'target review needs selected TARGET index')
    if a.get('target') is not None:
        require(isinstance(a.get('targetType'), str) and a['targetType'] in TARGET_TYPES, 'target type enum invalid')
    if a.get('score') is not None:
        score = a['score']
        require(type(score) in {int, float} and math.isfinite(score) and 0 <= score <= 1, 'score range invalid')
    # A derived compatibility view, explicitly not the provider's original JSON.
    derived = copy.deepcopy(output)
    derived['scopeHash'] = scope['scopeHash']
    return review_packet(derived, scope, payload)


def receive(attempt, observed_request, response):
    """Associate only within the caller's own invocation, never by a model hash.

    There is no network transport here. A caller supplying a response from the
    wrong invocation cannot be detected by content hashes alone.
    """
    validate_attempt(attempt)
    require(observed_request == attempt['requestBody'] and digest(observed_request) == attempt['requestHash'],
            'executed request differs from local attempt')
    output = parse_response(response, observed_request['model'])
    compatibility = adapt(output, attempt['selectedScope'], attempt['originalInput'])
    result = dict(schemaVersion=attempt['schemaVersion'], attemptHash=attempt['attemptHash'], attemptId=attempt['attemptId'],
                  requestHash=attempt['requestHash'], scopeHash=attempt['scopeHash'],
                  providerResponse=copy.deepcopy(response), responseHash=digest(response),
                  modelOutput=output, compatiblePacket=compatibility,
                  linkageSource='CALLER_LOCAL_INVOCATION', providerAuthenticityVerified=False,
                  derivedCompatibilityFields=['scopeHash'], responsesModified=False,
                  qualityGateMet=None, runtimeUseAuthorized=False)
    result['receiptHash'] = digest(result)
    return result


def validate_receipt(receipt, attempt):
    require(isinstance(receipt, dict) and receipt == receive(
        attempt, attempt['requestBody'], receipt['providerResponse']), 'receipt changed')
